import { Command } from '@commander-js/extra-typings';
import type { GlobalOpts } from '../../lib/client';
import { buildHelpText } from '../../lib/help-text';
import { outputResult } from '../../lib/output';
import { SYNTHETIC_EVENT_TYPES } from './trigger/fixtures';
import { forwardWebhookRequest } from './trigger/forward';
import { type PreparedRequest, prepareWebhookRequest } from './trigger/request';

function outputDryRun(request: PreparedRequest, opts: GlobalOpts): void {
  const result = {
    synthetic: true,
    dry_run: true,
    event_type: request.eventType,
    delivery_id: request.deliveryId,
    method: 'POST',
    url: request.url,
    headers: request.headers,
    body: request.body.toString('utf8'),
  };

  if (opts.json || opts.quiet || !process.stdout.isTTY) {
    outputResult(result, { json: true });
    return;
  }

  console.log('Synthetic webhook dry run (no request sent):');
  console.log(JSON.stringify(result, null, 2));
}

export const triggerWebhookCommand = new Command('trigger')
  .description('Send a signed synthetic webhook event to a local endpoint')
  .argument('<event-type>', 'Synthetic event type to prepare')
  .requiredOption(
    '--forward-to <url>',
    'HTTP(S) endpoint URL to receive the POST',
  )
  .option('--email-id <id>', 'Email ID (generated by default)')
  .option('--message-id <id>', 'Message ID (generated by default)')
  .option('--from <address>', 'Sender address')
  .option('--to <addresses...>', 'Recipient addresses')
  .option('--subject <subject>', 'Email subject')
  .option('--broadcast-id <id>', 'Broadcast ID (generated by default)')
  .option('--template-id <id>', 'Template ID (generated by default)')
  .option(
    '--tag <name=value...>',
    'Replace generated tags with name=value pairs',
  )
  .option('--event-created-at <timestamp>', 'Event creation time (ISO 8601)')
  .option('--email-created-at <timestamp>', 'Email creation time (ISO 8601)')
  .option('--bounce-type <type>', 'Bounce type (email.bounced only)')
  .option('--bounce-sub-type <subtype>', 'Bounce subtype (email.bounced only)')
  .option('--bounce-message <message>', 'Bounce message (email.bounced only)')
  .option('--delivery-id <id>', 'Reuse a delivery ID to test deduplication')
  .option('--dry-run', 'Show the signed request without sending it')
  .addHelpText(
    'after',
    buildHelpText({
      context: `Generate a Resend-shaped synthetic webhook event, sign it with RESEND_WEBHOOK_SECRET,\nand POST it directly to --forward-to. Set this variable to the same development-only\nsecret used by your app; the CLI does not load .env files automatically. This does\nnot call the Resend API.\n\nAvailable event types: ${SYNTHETIC_EVENT_TYPES.join(', ')}.\nUse focused options to override generated IDs, addresses, tags, and event data.`,
      output: `  {"synthetic":true,"event_type":"email.delivered","delivery_id":"msg_local_...","http_status":200,"duration_ms":12,"response_body":"accepted","response_truncated":false}`,
      errorCodes: [
        'unsupported_event_type',
        'webhook_secret_error',
        'invalid_forward_url',
        'invalid_option',
        'forward_timeout',
        'forward_error',
        'forward_http_error',
      ],
      setup: true,
      examples: [
        'resend webhooks trigger email.delivered --forward-to http://localhost:3000/webhooks/resend',
        'resend webhooks trigger email.delivered --forward-to http://localhost:3000/webhooks/resend --email-id 56761188-7520-42d8-8898-ff6fc54ce618 --to user@example.test',
        'resend webhooks trigger email.bounced --forward-to http://localhost:3000/webhooks/resend --delivery-id msg_local_repeatable_1',
        'resend webhooks trigger email.complained --forward-to http://localhost:3000/webhooks/resend --dry-run',
      ],
    }),
  )
  .action(async (eventType, options, command) => {
    const globalOpts = command.optsWithGlobals() as GlobalOpts;
    const request = prepareWebhookRequest(
      eventType,
      options.forwardTo,
      {
        emailId: options.emailId,
        messageId: options.messageId,
        from: options.from,
        to: options.to,
        subject: options.subject,
        broadcastId: options.broadcastId,
        templateId: options.templateId,
        tag: options.tag,
        eventCreatedAt: options.eventCreatedAt,
        emailCreatedAt: options.emailCreatedAt,
        bounceType: options.bounceType,
        bounceSubType: options.bounceSubType,
        bounceMessage: options.bounceMessage,
      },
      options.deliveryId,
      globalOpts,
    );

    if (options.dryRun) {
      outputDryRun(request, globalOpts);
      return;
    }

    const delivery = await forwardWebhookRequest(request, globalOpts);
    const result = {
      synthetic: true,
      event_type: request.eventType,
      delivery_id: request.deliveryId,
      http_status: delivery.httpStatus,
      duration_ms: delivery.durationMs,
      response_body: delivery.responseBody,
      response_truncated: delivery.responseTruncated,
    };
    if (globalOpts.json || globalOpts.quiet || !process.stdout.isTTY) {
      outputResult(result, { json: true });
      return;
    }

    console.log(
      `Synthetic event ${request.eventType} received HTTP ${delivery.httpStatus} from ${request.url}. This confirms the HTTP response only.`,
    );
    if (delivery.responseBody) {
      console.log(`Response: ${delivery.responseBody}`);
    }
    if (delivery.responseTruncated) {
      console.log('Response body truncated after 4 KiB.');
    }
  });
